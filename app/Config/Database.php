    public function __construct()
    {
        parent::__construct();

        // Timpa kredensial dari .env (EULT_DB_* / EULT_DBULT_*) agar
        // cukup ganti .env saat pindah server tanpa sentuh kode.
        $baca = static fn (string $kunci, string $bawaan = ''): string => ($v = env($kunci)) !== null && $v !== '' ? (string) $v : $bawaan;

        $this->default['hostname'] = $baca('EULT_DB_HOST', $this->default['hostname']);
        $this->default['port']     = (int) $baca('EULT_DB_PORT', (string) $this->default['port']);
        $this->default['database'] = $baca('EULT_DB_NAME', $this->default['database']);
        $this->default['username'] = $baca('EULT_DB_USER', $this->default['username']);
        $this->default['password'] = $baca('EULT_DB_PASS', $this->default['password']);

        $this->dbult['hostname'] = $baca('EULT_DBULT_HOST', $this->dbult['hostname']);
        $this->dbult['port']     = (int) $baca('EULT_DBULT_PORT', (string) $this->dbult['port']);
        $this->dbult['database'] = $baca('EULT_DBULT_NAME', $this->dbult['database']);
        $this->dbult['username'] = $baca('EULT_DBULT_USER', $this->dbult['username']);
        $this->dbult['password'] = $baca('EULT_DBULT_PASS', $this->dbult['password']);

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
